-- Mamá Qocha: esquema inicial PostgreSQL 18
-- Base prevista: mama_qocha. Este script crea tablas, no inserta datos.
-- La lógica transaccional de actualización de stock se implementará en la aplicación.

BEGIN;

CREATE TABLE IF NOT EXISTS locales (
 id_local BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE,
 direccion VARCHAR(250),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS proveedores (
 id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(160) NOT NULL,
 rut VARCHAR(20) UNIQUE,
 telefono VARCHAR(40),
 correo VARCHAR(160),
 direccion VARCHAR(250),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS productos (
 id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(160) NOT NULL UNIQUE,
 descripcion TEXT,
 unidad_medida VARCHAR(20) NOT NULL DEFAULT 'kg',
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_productos_unidad CHECK (unidad_medida IN ('kg','g','l','ml','unidad'))
);

CREATE TABLE IF NOT EXISTS usuarios (
 id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(160) NOT NULL,
 nombre_usuario VARCHAR(80) NOT NULL UNIQUE,
 hash_password TEXT,
 rol VARCHAR(30) NOT NULL DEFAULT 'operador',
 id_local BIGINT REFERENCES locales(id_local),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_usuarios_rol CHECK (rol IN ('administrador','operador'))
);

CREATE TABLE IF NOT EXISTS compras (
 id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_proveedor BIGINT NOT NULL REFERENCES proveedores(id_proveedor),
 id_local_receptor BIGINT NOT NULL REFERENCES locales(id_local),
 tipo_documento VARCHAR(40) NOT NULL DEFAULT 'factura',
 numero_documento VARCHAR(80) NOT NULL,
 fecha_compra DATE NOT NULL,
 fecha_recepcion DATE NOT NULL,
 observaciones TEXT,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_compras_fechas CHECK (fecha_recepcion >= fecha_compra),
 CONSTRAINT uq_compras_documento_proveedor UNIQUE (id_proveedor,tipo_documento,numero_documento)
);

CREATE TABLE IF NOT EXISTS detalle_compra (
 id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_compra BIGINT NOT NULL REFERENCES compras(id_compra),
 id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
 cantidad_recibida NUMERIC(12,3) NOT NULL CHECK (cantidad_recibida > 0),
 costo_unitario NUMERIC(12,2) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
 observaciones TEXT,
 CONSTRAINT uq_detalle_compra_producto UNIQUE (id_compra,id_producto)
);

CREATE TABLE IF NOT EXISTS lotes (
 id_lote BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_detalle_compra BIGINT NOT NULL REFERENCES detalle_compra(id_detalle_compra),
 codigo_lote_proveedor VARCHAR(100) NOT NULL,
 cantidad_inicial NUMERIC(12,3) NOT NULL CHECK (cantidad_inicial > 0),
 fecha_vencimiento DATE NOT NULL,
 fecha_recepcion DATE NOT NULL,
 temperatura_recepcion NUMERIC(4,1) DEFAULT 2.0,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_lote_detalle_codigo UNIQUE (id_detalle_compra,codigo_lote_proveedor)
);

CREATE TABLE IF NOT EXISTS stock_lote_local (
 id_stock BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_lote BIGINT NOT NULL REFERENCES lotes(id_lote),
 id_local BIGINT NOT NULL REFERENCES locales(id_local),
 cantidad NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_stock_lote_local UNIQUE (id_lote,id_local)
);

CREATE TABLE IF NOT EXISTS movimientos (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo_movimiento VARCHAR(30) NOT NULL CHECK (tipo_movimiento IN ('salida_cocina','traslado')),
 fecha_movimiento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 id_local_origen BIGINT NOT NULL REFERENCES locales(id_local),
 id_local_destino BIGINT REFERENCES locales(id_local),
 id_usuario BIGINT REFERENCES usuarios(id_usuario),
 referencia VARCHAR(100),
 observaciones TEXT,
 estado VARCHAR(20) NOT NULL DEFAULT 'confirmado'
   CHECK (estado IN ('borrador','confirmado','anulado')),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_movimientos_origen_destino CHECK (
  (tipo_movimiento = 'salida_cocina' AND id_local_destino IS NULL)
  OR
  (tipo_movimiento = 'traslado' AND id_local_destino IS NOT NULL AND id_local_destino <> id_local_origen)
 )
);

CREATE TABLE IF NOT EXISTS detalle_movimiento (
 id_detalle_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_movimiento BIGINT NOT NULL REFERENCES movimientos(id_movimiento),
 id_lote BIGINT NOT NULL REFERENCES lotes(id_lote),
 cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
 observaciones TEXT,
 CONSTRAINT uq_movimiento_lote UNIQUE (id_movimiento,id_lote)
);

CREATE TABLE IF NOT EXISTS recetas (
 id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL UNIQUE,
 categoria VARCHAR(60) NOT NULL,
 tiempo_preparacion_min INT DEFAULT 18,
 precio_venta NUMERIC(10,2) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS receta_ingredientes (
 id_receta_ingrediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_receta BIGINT NOT NULL REFERENCES recetas(id_receta) ON DELETE CASCADE,
 id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
 cantidad_kg NUMERIC(8,3) NOT NULL CHECK (cantidad_kg > 0),
 CONSTRAINT uq_receta_producto UNIQUE (id_receta, id_producto)
);

CREATE INDEX IF NOT EXISTS ix_compras_fecha ON compras(fecha_compra);
CREATE INDEX IF NOT EXISTS ix_compras_local_receptor ON compras(id_local_receptor);
CREATE INDEX IF NOT EXISTS ix_detalle_compra_producto ON detalle_compra(id_producto);
CREATE INDEX IF NOT EXISTS ix_lotes_vencimiento ON lotes(fecha_vencimiento);
CREATE INDEX IF NOT EXISTS ix_stock_local ON stock_lote_local(id_local);
CREATE INDEX IF NOT EXISTS ix_movimientos_fecha ON movimientos(fecha_movimiento);
CREATE INDEX IF NOT EXISTS ix_movimientos_origen ON movimientos(id_local_origen);
CREATE INDEX IF NOT EXISTS ix_movimientos_destino ON movimientos(id_local_destino);
CREATE INDEX IF NOT EXISTS ix_detalle_movimiento_lote ON detalle_movimiento(id_lote);
CREATE INDEX IF NOT EXISTS ix_receta_ingredientes_receta ON receta_ingredientes(id_receta);
CREATE INDEX IF NOT EXISTS ix_receta_ingredientes_producto ON receta_ingredientes(id_producto);

COMMIT;

-- Notas:
-- * No se insertan datos ficticios.
-- * La aplicación debe aplicar FEFO (vencimiento más próximo) y FIFO como desempate.
-- * Las salidas y traslados deben validar stock y actualizar cantidades e historial
--   en una única transacción PostgreSQL, con rollback si falla cualquier paso.
-- * Un traslado conserva el id_lote original; no crea un lote nuevo.
-- * Hacer respaldo antes de ejecutar en una base que ya contenga datos.
